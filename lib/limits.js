/**
 * 提炼退避的阈值常量 —— 单一真相源。
 *
 * 【为什么单独一个文件（2026-11-07）】这两个数原先在 `pipeline.js`（编排侧）
 * 和 `distill-state.js`（持久化侧）各定义了一份、值都是 3 / 2。两处注释甚至
 * 互相引用说"是同一个语义"—— 也就是说**改一处忘另一处**时，两份注释都会
 * 继续说它们是同一个语义，而实际行为已经漂了。这是典型的"两个真相源"。
 *
 * 放在这里而不是让一边 import 另一边，是因为两侧的职责不同：
 *   · pipeline.js 要保持"零依赖纯函数"（可单测、不碰 IO）
 *   · distill-state.js 要碰 fs
 * 让后者 import 前者会把两条不相关的依赖线缠在一起；抽成无依赖的常量模块最省事。
 *
 * 两个模块都**重新导出**这两个名字，所以旧的 import 路径不受影响。
 */

/**
 * 同一会话连续失败多少次后跳过。
 *
 * 为什么不无限重试：坏会话会一直排在队首，每轮吃掉一个名额，把好会话挤出去。
 * 为什么是 3：一次失败可能是网络抖动或模型状态差，两次都失败就已经不太像偶发。
 */
export const MAX_CONSECUTIVE_FAILURES = 3

/**
 * 连续多少次"成功但没有产出"后跳过。
 *
 * 与"失败"是两件事：失败可以重试，空产出（模型明确返回无料）重试大概率还是空。
 * 实测依据：29 轮记录里 68.6% 的会话未被标记，其中 15 轮 failures=0 却有
 * 184 个会话没产出 —— 它们反复占用队首名额，就是"每轮都是那几张老面孔"的来源。
 */
export const MAX_EMPTY_YIELDS = 2

/**
 * 多会话批里的失败，累计多少次后才当作"这个会话可能真有问题"而退避。
 *
 * 【为什么需要第三个阈值（2026-11-09）】原来的失败计数是**按批**记的：模型一次
 * 没吐 JSON，同批 3 个会话一起 +1，连撞 3 轮就集体永久封杀。实测 12 个被永久
 * 排除的会话里，5 个是 q=6.6–8.1 的强会话，本身毫无问题，只是恰好和坏会话分到
 * 同一批。LLM 输出不带 sid，"是哪一条导致失败"无法归因，所以换个办法：
 *   · 单会话批失败 → 归因明确，用 MAX_CONSECUTIVE_FAILURES（3）
 *   · 多会话批失败 → 只是"在这批里没成"，用这个更高的阈值（6）
 * 6 是 3 的 2 倍：多会话批本来就更容易连带，给两倍的容忍度；但真坏的会话
 * 依然会被挡住，只是慢一点。
 */
export const MAX_SUSPECTED_FAILURES = 6
